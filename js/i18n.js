/* Patrones para textos compuestos */
const I18N_PATTERNS = [
  [/^(\d+) obras?$/, (m, n) => `${n} ${n === "1" ? "work" : "works"}`],
  [/^Ver obras \((\d+)\)$/, (m, n) => `View works (${n})`],
  [/^Hasta (.+)$/, (m, x) => `Up to ${x}`],
  [/^(.+), obra de (.+)$/, (m, a, b) => `${tr(a)}, by ${b}`],
  [/^(.+), de (.+)$/, (m, a, b) => `${tr(a)}, by ${b}`],
  [/^Retrato ilustrativo de (.+)$/, (m, a) => `Illustrative portrait of ${a}`],
  [/^“(.+)” se agregó a tu selección$/, (m, a) => `“${tr(a)}” was added to your selection`],
  [/^© (\d+) (.+?)\. Todos los derechos reservados\.$/, (m, y, n) => `© ${y} ${n}. All rights reserved.`],
  [/^(.+) — inicio$/, (m, n) => `${n} — home`],
  [/^\/ (.+)$/, (m, a) => `/ ${tr(a)}`],
  [/^(.+) — (.+)$/, (m, a, b) => `${tr(a)} — ${tr(b)}`],
  [/^(.+) · (.+)$/, (m, a, b) => `${tr(a)} · ${tr(b)}`],
  [/^(.+)\. (Obra original .+)$/, (m, a, b) => `${tr(a)}. ${tr(b)}`]
];

let LANG = "es";
function buildDataDict() {
  (typeof OBRAS !== "undefined" ? OBRAS : []).forEach(o => {
    if (o.titulo_en) I18N_EN[o.titulo] = o.titulo_en;
    if (o.tecnica_en) I18N_EN[o.tecnica] = o.tecnica_en;
    if (o.descripcion_en) I18N_EN[o.descripcion] = o.descripcion_en;
  });
  (typeof ARTISTAS !== "undefined" ? ARTISTAS : []).forEach(a => {
    if (a.disciplina_en) I18N_EN[a.disciplina] = a.disciplina_en;
    if (a.bio_en) I18N_EN[a.bio] = a.bio_en;
  });
  if (typeof CONFIG !== "undefined" && CONFIG.lema) I18N_EN[CONFIG.lema] = I18N_EN[CONFIG.lema] || CONFIG.lema;
}
/* Traduce un texto en español al idioma activo */
function tr(s) {
  if (LANG === "es" || !s) return s;
  const k = s.trim();
  if (I18N_EN[k] !== undefined) return s.replace(k, I18N_EN[k]);
  for (const [re, fn] of I18N_PATTERNS) { const m = k.match(re); if (m) { const r = fn(...m); if (r !== k) return s.replace(k, r); } }
  return s;
}
window.t = tr;

const ORIG_TEXT = new WeakMap(), ORIG_ATTR = new WeakMap(), ATTRS = ["aria-label", "alt", "placeholder", "title"];
let docTitleOrig = null, applying = false;
function translateNode(root) {
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let n;
  while ((n = w.nextNode())) {
    if (!n.nodeValue.trim() || n.parentElement.closest("script,style,[data-no-i18n]")) continue;
    if (!ORIG_TEXT.has(n)) ORIG_TEXT.set(n, n.nodeValue);
    const v = tr(ORIG_TEXT.get(n)); if (n.nodeValue !== v) n.nodeValue = v;
  }
  const els = root.querySelectorAll ? [root, ...root.querySelectorAll("*")] : [];
  els.forEach(el => {
    if (!el.getAttribute) return;
    ATTRS.forEach(a => {
      if (!el.hasAttribute(a)) return;
      let m = ORIG_ATTR.get(el); if (!m) ORIG_ATTR.set(el, m = {});
      if (!(a in m)) m[a] = el.getAttribute(a);
      const v = tr(m[a]); if (el.getAttribute(a) !== v) el.setAttribute(a, v);
    });
  });
}
function applyLang() {
  applying = true;
  document.documentElement.lang = LANG === "en" ? "en" : "es-AR";
  if (docTitleOrig === null) docTitleOrig = document.title;
  document.title = tr(docTitleOrig);
  translateNode(document.body);
  const b = document.getElementById("langBtn");
  if (b) { b.textContent = LANG === "es" ? "EN" : "ES"; b.setAttribute("aria-label", LANG === "es" ? "Switch to English" : "Cambiar a español"); }
  applying = false;
}
function setLang(l) { LANG = l; localStorage.setItem("idioma", l); applyLang(); }
function initI18n() {
  buildDataDict();
  LANG = localStorage.getItem("idioma") || (typeof CONFIG !== "undefined" && CONFIG.idioma) || "es";
  applyLang();
  new MutationObserver(muts => {
    if (applying) return;
    muts.forEach(m => {
      if (m.type === "characterData") { const n = m.target; if (n.nodeValue !== tr(ORIG_TEXT.get(n) || "")) { ORIG_TEXT.set(n, n.nodeValue); } }
      if (m.type === "attributes" && ATTRS.includes(m.attributeName)) { const o = ORIG_ATTR.get(m.target); const cur = m.target.getAttribute(m.attributeName); if (o && cur !== tr(o[m.attributeName])) o[m.attributeName] = cur; }
    });
    applying = true; muts.forEach(m => { const t = m.type === "childList" ? m.target : (m.target.nodeType === 3 ? m.target.parentElement : m.target); if (t && t.isConnected) translateNode(t); }); applying = false;
    if (document.title !== tr(docTitleOrig)) { docTitleOrig = document.title; applying = true; document.title = tr(docTitleOrig); applying = false; }
  }).observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });
}
